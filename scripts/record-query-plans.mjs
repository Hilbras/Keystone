#!/usr/bin/env node
/**
 * Record query plans for the repository's own database.
 *
 * Reads real row counts and runs `EXPLAIN (ANALYZE, BUFFERS)` for the queries
 * the analysis flagged, writing `docs/performance/query-plans.md`.
 *
 * The point is not the pretty output. It is that a claim like *"this table has
 * no index, therefore this is a High-severity risk"* can be checked in four
 * minutes, and when it was checked in v3.1.0 it turned out to be wrong: at 145
 * rows a sequential scan is the correct plan. Counting `index()` declarations is
 * not the same as knowing whether a plan is right.
 *
 * Usage: node scripts/record-query-plans.mjs [--table <name>]
 */

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const databaseUrl = process.env.DATABASE_URL;
if (!databaseUrl) {
  console.error("DATABASE_URL is required. Set it and re-run.");
  process.exit(1);
}
const postgres = require("postgres");
const sql = postgres(databaseUrl);

const only = (() => {
  const i = process.argv.indexOf("--table");
  return i === -1 ? null : process.argv[i + 1];
})();

/**
 * The queries worth recording.
 *
 * `seqScanAcceptable` marks a sequential scan that is *correct* at this table's
 * size, with the reason. A gate that forbids every sequential scan would fail on
 * a small catalogue, and a gate that fails on correct behaviour gets disabled —
 * so the exception is explicit and carries its justification.
 */
const QUERIES = [
  {
    id: "org-membership-by-user",
    where: "requireOrgRole, every organization-scoped request",
    sql: "select org_id, role from org_memberships where user_id = $1::uuid",
  },
  {
    id: "organization-by-id",
    where: "request.state.org, every organization-scoped request",
    sql: "select id, name from organizations where id = $1::uuid",
  },
  {
    id: "permission-by-resource-action",
    where: "requirePermission",
    sql: "select id from permissions where resource = $1 and action = $2",
    // Bounded by the resource:action surface, not by user count. 145 rows.
    seqScanAcceptable: "a 145-row catalogue; a sequential scan reads one page and an index would only add write amplification",
  },
  {
    id: "role-permission-join",
    where: "requirePermission, role expansion",
    sql: "select p.id from role_permissions rp join permissions p on p.id = rp.permission_id where rp.role = $1",
    seqScanAcceptable: "292 rows on one side; the join is cheaper to scan than to index twice",
  },
  {
    id: "scim-group-members-batched",
    where: "SCIM group list, one query per page since v3.1.0",
    sql: "select user_id from scim_group_members where group_id = any($1::uuid[])",
  },
];

try {
  const tables = [
    "users", "organizations", "org_memberships", "audit_log", "refresh_tokens",
    "api_keys", "permissions", "role_permissions", "scim_groups", "scim_group_members",
  ];
  const counts = {};
  for (const t of tables) {
    const [row] = await sql.unsafe(`select count(*)::int as n from ${t}`);
    counts[t] = row.n;
  }

  const results = [];
  for (const q of QUERIES) {
    if (only && !q.id.includes(only)) continue;
    // Postgres cannot infer a parameter type that is not used, so the literals
    // are inlined rather than bound. These are plan-shape measurements against a
    // development database, not queries that will ever run.
    const params = [];
    const inlined = q.sql
      .replace(/\$1::uuid/g, "'00000000-0000-0000-0000-000000000000'::uuid")
      .replace(/\$1::uuid\[\]/g, "ARRAY[]::uuid[]")
      .replace(/\$1/g, "'admin'")
      .replace(/\$2/g, "'create'");
    let plan;
    let exec;
    try {
      const rows = await sql.unsafe("EXPLAIN (ANALYZE, BUFFERS) " + inlined, params);
      plan = rows.map((r) => Object.values(r)[0]);
      exec = plan.find((l) => /Execution Time/.test(l)) || "";
    } catch (err) {
      plan = [`ERROR: ${err.message.split("\n")[0]}`];
      exec = "";
    }
    const seqScans = plan.filter((l) => /Seq Scan/.test(l)).length;
    const indexScans = plan.filter((l) => /Index (Scan|Only Scan)/.test(l)).length;
    results.push({ ...q, plan, exec, seqScans, indexScans });
  }

  const out = [];
  out.push("## Measured query plans");
  out.push("");
  out.push(`Generated by \`npm run plans:record\` on ${new Date().toISOString().slice(0, 10)}.`);
  out.push("");
  out.push("| Table | Rows |");
  out.push("| --- | --- |");
  for (const [t, n] of Object.entries(counts)) out.push(`| \`${t}\` | ${n} |`);
  out.push("");
  for (const r of results) {
    out.push(`### \`${r.id}\``);
    out.push("");
    out.push(`**Where:** ${r.where}`);
    out.push("");
    out.push("```sql");
    out.push(r.sql);
    out.push("```");
    out.push("");
    out.push("```");
    out.push(...r.plan);
    out.push("```");
    out.push("");
    out.push(`- sequential scans: **${r.seqScans}**`);
    out.push(`- index scans: **${r.indexScans}**`);
    if (r.exec) out.push(`- \`${r.exec.trim()}\``);
    if (r.seqScanAcceptable) {
      out.push("");
      out.push(`**The sequential scan is correct** — ${r.seqScanAcceptable}.`);
    }
    out.push("");
  }

  console.log(out.join("\n"));
} finally {
  await sql.end();
}
