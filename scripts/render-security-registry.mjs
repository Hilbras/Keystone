#!/usr/bin/env node
/**
 * Render docs/security/registry.md from docs/security/registry.json.
 *
 * The registry is machine-readable so a test can enforce it, and it is also
 * documentation an operator reads. Generating the prose from the same file means
 * the two cannot disagree — a hand-maintained table would drift the first time a
 * finding was added.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const registry = JSON.parse(
  fs.readFileSync(path.join(root, "docs", "security", "registry.json"), "utf8")
);

const SEVERITY_ORDER = ["critical", "high", "medium", "low"];
const bySeverity = Object.fromEntries(SEVERITY_ORDER.map((s) => [s, []]));
for (const entry of registry.entries) bySeverity[entry.severity]?.push(entry);

const outPath = path.join(root, "docs", "security", "registry.md");
const out = [];
out.push("# Security regression registry");
out.push("");
out.push("<!-- Generated by scripts/render-security-registry.mjs from docs/security/registry.json. Do not edit by hand. -->");
out.push("");
out.push(
  "Every vulnerability found in Keystone, the fix, the test that would fail without it, " +
    "and where it is documented. The registry is validated by `npm run registry:check`, " +
    "which fails if an entry names a test that does not exist, if a security suite is claimed " +
    "by no entry, or if a mandatory attack class is uncovered."
);
out.push("");
out.push(`**${registry.entries.length} findings.**`);
out.push("");
out.push("| Severity | Count |");
out.push("| --- | --- |");
for (const severity of SEVERITY_ORDER) {
  out.push(`| ${severity} | ${bySeverity[severity].length} |`);
}
out.push("");
if (registry.scope) {
  out.push("## Scope");
  out.push("");
  out.push(registry.scope.decision);
  out.push("");
  out.push("**In scope**");
  out.push("");
  for (const item of registry.scope.in_scope) out.push(`- ${item}`);
  out.push("");
  out.push("**Excluded, each with its reason and its cost**");
  out.push("");
  for (const item of registry.scope.excluded) {
    out.push(`- \`${item.what}\` — ${item.why}${item.cost ? ` **Cost:** ${item.cost}` : ""}`);
  }
  out.push("");
  out.push(registry.scope.why_not_src_only);
  out.push("");
}
out.push("## Mandatory attack classes");
out.push("");
out.push("The CI pipeline must exercise each of these. Every one is claimed by at least one entry above; the check is mechanical, not a convention.");
out.push("");
out.push("| Attack class | Findings |");
out.push("| --- | --- |");
for (const cls of registry.mandatoryAttackClasses) {
  const ids = registry.entries.filter((e) => (e.covers ?? []).includes(cls)).map((e) => e.id);
  out.push(`| \`${cls}\` | ${ids.join(", ") || "**none**"} |`);
}
out.push("");

for (const severity of SEVERITY_ORDER) {
  const entries = bySeverity[severity];
  if (entries.length === 0) continue;
  out.push(`## ${severity[0].toUpperCase()}${severity.slice(1)}`);
  out.push("");
  for (const entry of entries) {
    out.push(`### ${entry.id} — ${entry.title}`);
    out.push("");
    out.push(`*Fixed in v${entry.release}. Component: \`${entry.component}\`.*`);
    out.push("");
    out.push(`**Issue.** ${entry.issue}`);
    out.push("");
    out.push(`**Fix.** ${entry.fix}`);
    out.push("");
    out.push(`**Test.** \`${entry.test}\``);
    out.push("");
    // Relative to *this* document (docs/security/registry.md), not the repo root.
    const docHref = path.relative(path.dirname(outPath), path.join(root, entry.documentation));
    out.push(`**Documentation.** [${entry.documentation}](${docHref})`);
    if (entry.covers?.length) {
      out.push("");
      out.push(`**Attack classes.** ${entry.covers.map((c) => `\`${c}\``).join(", ")}`);
    }
    out.push("");
  }
}

fs.writeFileSync(path.join(root, "docs", "security", "registry.md"), out.join("\n"));
console.log(`Wrote docs/security/registry.md (${registry.entries.length} findings).`);
